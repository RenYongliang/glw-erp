  statementLagMonths: number
  /** 出单日 1-31。 */
  statementDay: number
  dueRule: DueRule
  creditDays: number
  creditBasis: CreditBasis
  /** CALENDAR：账单结束月后第 N 个月。 */
  dueMonthOffset: number
  /** CALENDAR：约定日，0 表示月末。 */
  dueDay: number

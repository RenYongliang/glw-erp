package com.glw.backend.finance;

import jakarta.validation.constraints.*;
import lombok.Data;
import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;

public final class FinanceModels {
    private FinanceModels() {}

    @Data public static class Query {
        @NotNull @Pattern(regexp = "AR|AP") private String direction = "AR";
        private Long partnerId;
        /** 按业务订单过滤开项；预付款核销时使用。 */
        private Long orderId;
        @Pattern(regexp = "\\d{4}-(0[1-9]|1[0-2])") private String period;
        @Size(max = 128) private String keyword = "";
        @Size(max = 30) private String status;
        private Boolean unsettledOnly;
        private Boolean settledOnly;
        private Boolean overdueOnly;
        /** 只看待签收（应收未签收）的记录。 */
        private Boolean pendingBasisOnly;
        @Min(1) @Max(1000000) private int pageNo = 1;
        @Min(1) @Max(200) private int pageSize = 20;
        public int getOffset() { return Math.multiplyExact(pageNo - 1, pageSize); }
    }
    public record Page<T>(List<T> records, long total) {}
    @Data public static class OpenItem {
        private Long id, sourceId, sourceLineId, orderId, orderLineId, partnerId, productId, statementId;
        private String direction, sourceType, sourceNo, orderNo, partnerOrderNo, partnerName, statementNo;
        private String brand, partNo, packageType, currency, period, settleMonth, reconcileStatus;
        private Integer quantity, taxIncluded, taxRate, basisReady;
        private BigDecimal unitPrice, netAmount, taxAmount, grossAmount, settledAmount;
        private LocalDate bizDate, basisDate, periodStart, periodEnd, dueDate;
        private LocalDateTime createdAt;
    }
    @Data public static class Statement {
        private Long id, partnerId, templateId;
        private Integer templateVersion;
        private String statementNo, direction, partnerName, period, settleMonth, currency, status, remark;
        private Integer autoGenerated;
        private BigDecimal grossAmount, settledAmount;
        private LocalDate periodStart, periodEnd, dueDate;
        private LocalDateTime createdAt, sentAt, confirmedAt;
    }
    @Data public static class Payment {
        private Long id, partnerId, orderId;
        private String paymentNo, requestKey, direction, orderNo, paymentType, partnerName, currency, bankReference, remark, status;
        private LocalDate paymentDate;
        private BigDecimal amount, allocatedAmount;
        private LocalDateTime createdAt;
    }
    @Data public static class Allocation {
        private Long id, paymentId, openItemId;
        private String requestKey, status, sourceNo, orderNo, paymentNo;
        private BigDecimal amount;
        private LocalDateTime createdAt, reversedAt;
    }
    /** 结算档案：某往来单位在某方向下的账单周期、出单与到期规则。 */
    @Data public static class Profile {
        private Long id;
        @NotNull @Pattern(regexp = "AR|AP") private String direction;
        /** 0 表示公司默认方案行；客户档案必须填真实往来单位。 */
        @NotNull @Min(0) private Long partnerId;
        private String partnerName;
        /** 截止日（1-31）；为空表示按自然月切分账单。 */
        @Min(1) @Max(31) private Integer cutoffDay;
        /** 每份账单覆盖的月份数，如双月结为 2。 */
        @Min(1) @Max(12) private int cycleMonths = 1;
        /** 出单月 = 账单结束月 + N。 */
        @Min(0) @Max(12) private int statementLagMonths = 1;
        /** 出单日（1-31，超出当月天数取月末）。 */
        @Min(1) @Max(31) private int statementDay = 1;
        /** 到期日算法：固定天数 CREDIT_DAYS，或固定日历日 CALENDAR。 */
        @NotNull @Pattern(regexp = "CREDIT_DAYS|CALENDAR") private String dueRule = "CREDIT_DAYS";
        /** CREDIT_DAYS：账期天数。 */
        @Min(0) @Max(3650) private int creditDays;
        /** CREDIT_DAYS：起算点。 */
        @NotNull @Pattern(regexp = "PERIOD_END|ISSUE_DATE|ISSUE_MONTH_END") private String creditBasis = "PERIOD_END";
        /** CALENDAR：账单结束月后第 N 个月，0 表示当月。 */
        @Min(0) @Max(12) private int dueMonthOffset;
        /** CALENDAR：约定日，0 表示月末。 */
        @Min(0) @Max(31) private int dueDay;
        /** 是否参与自动出单。 */
        private Boolean autoGenerate = Boolean.FALSE;
        /** 对账依据：AR 可选 SIGNED/INBOUND，AP 固定 INBOUND。 */
        @Pattern(regexp = "SIGNED|INBOUND") private String reconcileBasis;
        /** 方案来源：DEFAULT=复制公司默认方案（只读），CUSTOM=自定义；partner_id=0 的公司默认行固定 CUSTOM。 */
        @Pattern(regexp = "DEFAULT|CUSTOM") private String planSource = "CUSTOM";
    }

    /** 保存结算档案的结果：同步了多少个客户默认行、重算了多少条未出账记录。 */
    public record SaveProfileResult(int syncedPartners, int recalculatedItems) {}
    @Data public static class Partner {
        private Long id;
        private String name, shortName;
    }
    @Data public static class PartnerInfo {
        private Long id;
        private String name, contact, phone;
    }
    @Data public static class StatementTemplate {
        private Long id, partnerId;
        private String docType, direction, format, name, fileName;
        private Integer version, isDefault, enabled;
        /** 是否可视化布局模板（可在设计器中继续编辑）。 */
        private Boolean hasLayout;
        private LocalDateTime createdAt;
    }
    public record BuiltinTemplate(String key, String name, String description, String format) {}
    @Data public static class Generate {
        @NotEmpty @Size(max = 1000) private List<@NotNull @Positive Long> openItemIds;
        @Size(max = 500) private String remark = "";
    }
    @Data public static class PaymentInput {
        @NotBlank @Size(max = 64) private String requestKey;
        @NotNull @Pattern(regexp = "AR|AP") private String direction;
        /** 从订单直接收付款时关联的订单ID。 */
        private Long orderId;
        @NotNull @Positive private Long partnerId;
        @NotNull private LocalDate paymentDate;
        @NotNull @DecimalMin("0.01") @Digits(integer = 12, fraction = 4) private BigDecimal amount;
        @NotNull @Size(max = 128) private String bankReference = "";
        @NotNull @Size(max = 500) private String remark = "";
    }
    @Data public static class Allocate {
        @NotBlank @Size(max = 64) private String requestKey;
        @NotNull @Positive private Long paymentId;
        @NotNull @Positive private Long openItemId;
        @NotNull @DecimalMin("0.01") @Digits(integer = 12, fraction = 4) private BigDecimal amount;
    }
    /** 从订单直接收付款：创建收付款单并核销该订单下已对账确认的开项。 */
    @Data public static class SettleOrderInput {
        /** 幂等键，最长 40 位，服务端会为每笔核销追加开项 id。 */
        @NotBlank @Size(max = 40) private String requestKey;
        @NotNull @Pattern(regexp = "AR|AP") private String direction;
        @NotNull @Positive private Long orderId;
        @NotNull private LocalDate paymentDate;
        @NotNull @DecimalMin("0.01") @Digits(integer = 12, fraction = 4) private BigDecimal amount;
        @NotNull @Size(max = 128) private String bankReference = "";
        @NotNull @Size(max = 500) private String remark = "";
    }
    @Data public static class SettleOrderResult {
        private Payment payment;
        private List<Allocation> allocations;
        /** 该订单当前未结金额（含尚未对账确认的部分）。 */
        private BigDecimal orderOutstanding;
        private BigDecimal allocatedAmount;
        private BigDecimal unallocatedAmount;
    }
    public record Summary(BigDecimal grossAmount, BigDecimal settledAmount, BigDecimal outstandingAmount,
                          BigDecimal overdueAmount, BigDecimal unallocatedAmount) {}
    public record StatementDetail(Statement statement, List<OpenItem> items, List<Allocation> allocations) {}
    public record PaymentDetail(Payment payment, List<Allocation> allocations) {}
}
